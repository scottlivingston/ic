fn main() {
    let faces: [(&str, &[[u8; GRID_WIDTH]; GRID_HEIGHT]); 4] = [
        ("default", &FACE_DEFAULT),
        ("default_talking", &FACE_TALKING),
        ("angry", &FACE_ANGRY),
        ("angry_talking", &FACE_ANGRY_TALKING),
    ];

    for (name, pattern) in faces {
        let mut img = RgbImage::new(GRID_WIDTH as u32, GRID_HEIGHT as u32);
        for (y, row) in pattern.iter().enumerate() {
            for (x, &pixel) in row.iter().enumerate() {
                let color = if pixel == 1 {
                    Rgb([255, 255, 255])
                } else {
                    Rgb([0, 0, 0])
                };
                img.put_pixel(x as u32, y as u32, color);
            }
        }
        let path = format!("src/assets/faces/{}.png", name);
        img.save(&path).unwrap();
        println!("Generated: {}", path);
    }
    println!("Done! Generated 4 face images.");
}
