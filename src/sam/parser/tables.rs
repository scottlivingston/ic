/// Get phoneme length (unstressed)
#[inline]
pub fn phoneme_length(index: usize) -> u8 {
    if index < COMBINED_PHONEME_LENGTH.len() {
        (COMBINED_PHONEME_LENGTH[index] & 0xFF) as u8
    } else {
        0
    }
}

/// Get stressed phoneme length
#[inline]
pub fn phoneme_stressed_length(index: usize) -> u8 {
    if index < COMBINED_PHONEME_LENGTH.len() {
        (COMBINED_PHONEME_LENGTH[index] >> 8) as u8
    } else {
        0
    }
}

/// Find phoneme index by name
pub fn find_phoneme(name: &str) -> Option<usize> {
    PHONEME_NAME_TABLE.iter().position(|&n| n == name)
}
