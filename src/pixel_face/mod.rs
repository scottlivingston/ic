/// Pack a 40x30 u8 grid into 10 vec4<u32> for shader
fn pack_face_pattern(grid: &[[u8; GRID_WIDTH]; GRID_HEIGHT]) -> [[u32; 4]; 10] {
    let mut packed = [[0u32; 4]; 10];
    for row in 0..GRID_HEIGHT {
        for col in 0..GRID_WIDTH {
            if grid[row][col] != 0 {
                let bit_index = row * GRID_WIDTH + col;
                let word_index = bit_index / 32;
                let bit_offset = bit_index % 32;
                let vec_index = word_index / 4;
                let vec_component = word_index % 4;
                packed[vec_index][vec_component] |= 1 << bit_offset;
            }
        }
    }
    packed
}

pub struct PixelFacePlugin;

impl Plugin for PixelFacePlugin {
    fn build(&self, app: &mut App) {
        embedded_asset!(app, "shaders/crt_pixel.wgsl");

        app.init_resource::<CrtEffects>()
            .init_resource::<SpeakingState>()
            .add_plugins(ExtractComponentPlugin::<PixelFaceSettings>::default())
            .add_systems(Update, update_effects_from_events)
            .add_systems(Update, sync_pixel_face_settings);

        let Some(render_app) = app.get_sub_app_mut(RenderApp) else {
            return;
        };

        render_app
            .add_systems(RenderStartup, init_pixel_face_pipeline)
            .add_render_graph_node::<ViewNodeRunner<PixelFaceNode>>(Core2d, PixelFaceLabel)
            .add_render_graph_edges(
                Core2d,
                (
                    Node2d::Tonemapping,
                    PixelFaceLabel,
                    Node2d::EndMainPassPostProcessing,
                ),
            );
    }
}

