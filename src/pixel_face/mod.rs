/// Uniform struct for shader - must match WGSL layout exactly
#[derive(ShaderType, Clone, Copy, bytemuck::Pod, bytemuck::Zeroable)]
#[repr(C)]
struct PixelFaceSettingsUniform {
    glow_enabled: u32,
    glow_intensity: f32,
    scanlines_enabled: u32,
    scanline_opacity: f32,
    flicker_enabled: u32,
    flicker_amount: f32,
    curvature_enabled: u32,
    curvature_amount: f32,
    grid_enabled: u32,
    time: f32,
    screen_size: Vec2,
    pixel_size: f32,
    // Padding to align face_pattern at 16-byte boundary (offset 64)
    _padding: [f32; 3],
    // 10 vec4<u32> for 16-byte alignment
    face_pattern: [[u32; 4]; 10],
}

impl From<&PixelFaceSettings> for PixelFaceSettingsUniform {
    fn from(settings: &PixelFaceSettings) -> Self {
        Self {
            glow_enabled: settings.glow_enabled,
            glow_intensity: settings.glow_intensity,
            scanlines_enabled: settings.scanlines_enabled,
            scanline_opacity: settings.scanline_opacity,
            flicker_enabled: settings.flicker_enabled,
            flicker_amount: settings.flicker_amount,
            curvature_enabled: settings.curvature_enabled,
            curvature_amount: settings.curvature_amount,
            grid_enabled: settings.grid_enabled,
            time: settings.time,
            screen_size: Vec2::new(settings.screen_width, settings.screen_height),
            pixel_size: settings.pixel_size,
            _padding: [0.0; 3],
            face_pattern: settings.face_pattern,
        }
    }
}

fn sync_pixel_face_settings(
    effects: Res<CrtEffects>,
    time: Res<Time>,
    windows: Query<&Window>,
    speaking: Res<SpeakingState>,
    mut cameras: Query<&mut PixelFaceSettings, With<Camera2d>>,
) {
    let Ok(window) = windows.single() else {
        return;
    };
    let Ok(mut settings) = cameras.single_mut() else {
        return;
    };

    // CRT effects from admin panel
    settings.glow_enabled = effects.glow_enabled as u32;
    settings.glow_intensity = effects.glow_intensity;
    settings.scanlines_enabled = effects.scanlines_enabled as u32;
    settings.scanline_opacity = effects.scanline_opacity;
    settings.flicker_enabled = effects.flicker_enabled as u32;
    settings.flicker_amount = effects.flicker_amount;
    settings.curvature_enabled = effects.curvature_enabled as u32;
    settings.curvature_amount = effects.curvature_amount;
    settings.grid_enabled = effects.grid_enabled as u32;
    settings.time = time.elapsed_secs();
    settings.screen_width = window.width();
    settings.screen_height = window.height();

    // Face pattern based on speaking state and face type - alternate at 12fps when speaking
    settings.face_pattern = if speaking.speaking {
        // Alternate between open/closed mouth at 12fps
        let frame = (time.elapsed_secs() * 12.0) as u32 % 2;
        match speaking.face_type {
            FaceType::Default => {
                if frame == 0 {
                    pack_face_pattern(&FACE_TALKING)
                } else {
                    pack_face_pattern(&FACE_DEFAULT)
                }
            }
            FaceType::Angry => {
                if frame == 0 {
                    pack_face_pattern(&FACE_ANGRY_TALKING)
                } else {
                    pack_face_pattern(&FACE_ANGRY)
                }
            }
        }
    } else {
        pack_face_pattern(&FACE_DEFAULT)
    };
}

#[derive(Default)]
struct PixelFaceNode;

impl ViewNode for PixelFaceNode {
    type ViewQuery = (&'static ViewTarget, &'static PixelFaceSettings);

    fn run(
        &self,
        _graph: &mut RenderGraphContext,
        render_context: &mut RenderContext,
        (view_target, settings): bevy::ecs::query::QueryItem<Self::ViewQuery>,
        world: &World,
    ) -> Result<(), NodeRunError> {
        let pipeline = world.resource::<PixelFacePipeline>();
        let pipeline_cache = world.resource::<PipelineCache>();

        let Some(render_pipeline) = pipeline_cache.get_render_pipeline(pipeline.pipeline_id) else {
            return Ok(());
        };

        let post_process = view_target.post_process_write();

        // Update cached uniform buffer with current settings
        let uniform = PixelFaceSettingsUniform::from(settings);
        let render_queue = world.resource::<RenderQueue>();
        render_queue.write_buffer(&pipeline.uniform_buffer, 0, bytemuck::bytes_of(&uniform));

        let bind_group = render_context.render_device().create_bind_group(
            "pixel_face_bind_group",
            &pipeline.layout,
            &BindGroupEntries::sequential((
                post_process.source,
                &pipeline.sampler,
                pipeline.uniform_buffer.as_entire_binding(),
            )),
        );

        let mut render_pass = render_context.begin_tracked_render_pass(RenderPassDescriptor {
            label: Some("pixel_face_pass"),
            color_attachments: &[Some(RenderPassColorAttachment {
                view: post_process.destination,
                depth_slice: None,
                resolve_target: None,
                ops: Operations::default(),
            })],
            depth_stencil_attachment: None,
            timestamp_writes: None,
            occlusion_query_set: None,
        });

        render_pass.set_render_pipeline(render_pipeline);
        render_pass.set_bind_group(0, &bind_group, &[]);
        render_pass.draw(0..3, 0..1);

        Ok(())
    }
}

#[derive(Resource)]
struct PixelFacePipeline {
    layout: BindGroupLayout,
    sampler: Sampler,
    pipeline_id: CachedRenderPipelineId,
    uniform_buffer: Buffer,
}

impl PixelFacePipeline {
    fn new(
        render_device: &RenderDevice,
        asset_server: &AssetServer,
        pipeline_cache: &PipelineCache,
        fullscreen_shader: &FullscreenShader,
    ) -> Self {
        let layout = render_device.create_bind_group_layout(
            "pixel_face_bind_group_layout",
            &BindGroupLayoutEntries::sequential(
                ShaderStages::FRAGMENT,
                (
                    texture_2d(TextureSampleType::Float { filterable: true }),
                    sampler(SamplerBindingType::Filtering),
                    uniform_buffer::<PixelFaceSettingsUniform>(false),
                ),
            ),
        );

        let sampler = render_device.create_sampler(&SamplerDescriptor::default());

        // Create cached uniform buffer (will be updated each frame)
        let uniform_buffer = render_device.create_buffer(&BufferDescriptor {
            label: Some("pixel_face_settings_buffer"),
            size: std::mem::size_of::<PixelFaceSettingsUniform>() as u64,
            usage: BufferUsages::UNIFORM | BufferUsages::COPY_DST,
            mapped_at_creation: false,
        });

        let shader = asset_server.load::<Shader>("embedded://ic/pixel_face/shaders/crt_pixel.wgsl");

        let pipeline_id = pipeline_cache.queue_render_pipeline(RenderPipelineDescriptor {
            label: Some("pixel_face_pipeline".into()),
            layout: vec![layout.clone()],
            vertex: fullscreen_shader.to_vertex_state(),
            fragment: Some(FragmentState {
                shader,
                targets: vec![Some(ColorTargetState {
                    format: TextureFormat::Rgba8UnormSrgb,
                    blend: None,
                    write_mask: ColorWrites::ALL,
                })],
                ..default()
            }),
            ..default()
        });

        Self {
            layout,
            sampler,
            pipeline_id,
            uniform_buffer,
        }
    }
}

fn init_pixel_face_pipeline(
    mut commands: Commands,
    render_device: Res<RenderDevice>,
    asset_server: Res<AssetServer>,
    pipeline_cache: Res<PipelineCache>,
    fullscreen_shader: Res<FullscreenShader>,
) {
    commands.insert_resource(PixelFacePipeline::new(
        &render_device,
        &asset_server,
        &pipeline_cache,
        &fullscreen_shader,
    ));
}
