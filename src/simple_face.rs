/// Get lit pixel positions from a pattern
fn get_lit_pixels(pattern: &[[u8; GRID_WIDTH]; GRID_HEIGHT]) -> Vec<(usize, usize)> {
    let mut pixels = Vec::with_capacity(64);
    for (row, cols) in pattern.iter().enumerate() {
        for (col, &lit) in cols.iter().enumerate() {
            if lit != 0 {
                pixels.push((col, row));
            }
        }
    }
    pixels
}

/// Convert grid position to screen position
fn grid_to_screen(col: usize, row: usize) -> Vec2 {
    let x = (col as f32 - GRID_WIDTH as f32 / 2.0) * PIXEL_SIZE + PIXEL_SIZE / 2.0;
    let y = (GRID_HEIGHT as f32 / 2.0 - row as f32) * PIXEL_SIZE - PIXEL_SIZE / 2.0;
    Vec2::new(x, y)
}

pub struct SimpleFacePlugin;

impl Plugin for SimpleFacePlugin {
    fn build(&self, app: &mut App) {
        // Initialize SpeakingState (shared with audio module)
        app.init_resource::<SpeakingState>()
            .init_resource::<FaceAnimation>()
            .add_systems(OnEnter(AppMode::Normal), spawn_face_sprites)
            .add_systems(OnExit(AppMode::Normal), despawn_face_sprites)
            .add_systems(
                Update,
                update_face_sprites.run_if(in_state(AppMode::Normal)),
            );
    }
}

/// Marker component for face pixel sprites
#[derive(Component)]
struct FacePixelSprite;

/// Resource tracking active sprites and entity pool
#[derive(Resource)]
struct FaceSpriteState {
    /// Map from (col, row) to active entity
    active: HashMap<(usize, usize), Entity>,
    /// Pool of hidden entities ready for reuse
    pool: Vec<Entity>,
    /// Currently displayed pattern
    current_pattern: &'static [[u8; GRID_WIDTH]; GRID_HEIGHT],
}

impl Default for FaceSpriteState {
    fn default() -> Self {
        Self {
            active: HashMap::new(),
            pool: Vec::with_capacity(64),
            current_pattern: &FACE_DEFAULT,
        }
    }
}

/// Local animation state
#[derive(Resource)]
struct FaceAnimation {
    timer: Timer,
    mouth_open: bool,
}

impl Default for FaceAnimation {
    fn default() -> Self {
        Self {
            timer: Timer::from_seconds(1.0 / 12.0, TimerMode::Repeating),
            mouth_open: false,
        }
    }
}

fn spawn_face_sprites(mut commands: Commands) {
    let mut state = FaceSpriteState::default();

    // Spawn sprites only for lit pixels in default face
    let lit_pixels = get_lit_pixels(&FACE_DEFAULT);
    for (col, row) in lit_pixels {
        let pos = grid_to_screen(col, row);
        let entity = commands
            .spawn((
                FacePixelSprite,
                Sprite {
                    color: FACE_COLOR,
                    custom_size: Some(Vec2::new(PIXEL_SIZE, PIXEL_SIZE)),
                    ..default()
                },
                Transform::from_xyz(pos.x, pos.y, 0.0),
            ))
            .id();
        state.active.insert((col, row), entity);
    }

    commands.insert_resource(state);
}

fn despawn_face_sprites(
    mut commands: Commands,
    state: Option<Res<FaceSpriteState>>,
    pool_query: Query<Entity, With<FacePixelSprite>>,
) {
    // Despawn all face sprites
    for entity in pool_query.iter() {
        commands.entity(entity).despawn();
    }
    if state.is_some() {
        commands.remove_resource::<FaceSpriteState>();
    }
}

fn update_face_sprites(
    mut commands: Commands,
    time: Res<Time>,
    speaking: Res<SpeakingState>,
    mut animation: ResMut<FaceAnimation>,
    state: Option<ResMut<FaceSpriteState>>,
    mut transforms: Query<&mut Transform, With<FacePixelSprite>>,
    mut visibility_query: Query<&mut Visibility, With<FacePixelSprite>>,
) {
    let Some(mut state) = state else {
        return;
    };

    // Determine which pattern to show
    let pattern: &'static [[u8; GRID_WIDTH]; GRID_HEIGHT] = if speaking.speaking {
        animation.timer.tick(time.delta());
        if animation.timer.just_finished() {
            animation.mouth_open = !animation.mouth_open;
        }

        match (speaking.face_type, animation.mouth_open) {
            (FaceType::Default, false) => &FACE_DEFAULT,
            (FaceType::Default, true) => &FACE_TALKING,
            (FaceType::Angry, false) => &FACE_ANGRY,
            (FaceType::Angry, true) => &FACE_ANGRY_TALKING,
        }
    } else {
        animation.mouth_open = false;
        &FACE_DEFAULT
    };

    // Skip if pattern unchanged
    if std::ptr::eq(pattern, state.current_pattern) {
        return;
    }
    state.current_pattern = pattern;

    // Get new lit pixels
    let new_lit: Vec<(usize, usize)> = get_lit_pixels(pattern);

    // Find pixels to remove (in active but not in new_lit)
    let to_remove: Vec<(usize, usize)> = state
        .active
        .keys()
        .filter(|pos| !new_lit.contains(pos))
        .copied()
        .collect();

    // Find pixels to add (in new_lit but not in active)
    let to_add: Vec<(usize, usize)> = new_lit
        .iter()
        .filter(|pos| !state.active.contains_key(pos))
        .copied()
        .collect();

    // Remove old pixels - move to pool
    for pos in to_remove {
        if let Some(entity) = state.active.remove(&pos) {
            // Hide and add to pool
            if let Ok(mut vis) = visibility_query.get_mut(entity) {
                *vis = Visibility::Hidden;
            }
            state.pool.push(entity);
        }
    }

    // Add new pixels - reuse from pool or spawn new
    for (col, row) in to_add {
        let screen_pos = grid_to_screen(col, row);

        if let Some(entity) = state.pool.pop() {
            // Reuse pooled entity
            if let Ok(mut transform) = transforms.get_mut(entity) {
                transform.translation.x = screen_pos.x;
                transform.translation.y = screen_pos.y;
            }
            if let Ok(mut vis) = visibility_query.get_mut(entity) {
                *vis = Visibility::Visible;
            }
            state.active.insert((col, row), entity);
        } else {
            // Spawn new entity
            let entity = commands
                .spawn((
                    FacePixelSprite,
                    Sprite {
                        color: FACE_COLOR,
                        custom_size: Some(Vec2::new(PIXEL_SIZE, PIXEL_SIZE)),
                        ..default()
                    },
                    Transform::from_xyz(screen_pos.x, screen_pos.y, 0.0),
                ))
                .id();
            state.active.insert((col, row), entity);
        }
    }
}
